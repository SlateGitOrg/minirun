//go:build ignore

// mktables generates ztables.go, the syscall name -> number tables for the
// architectures minirun can compile seccomp filters for. The source of truth
// is golang.org/x/sys/unix's zsysnum_linux_<arch>.go, which is itself
// generated from the kernel's asm/unistd.h.
//
// Usage (from the repository root):
//
//	go run ./internal/seccomp/mktables.go > internal/seccomp/ztables.go
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var lineRE = regexp.MustCompile(`^\s*SYS_([A-Z0-9_]+)\s*=\s*(\d+)\s*$`)

func main() {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "golang.org/x/sys").Output()
	if err != nil {
		log.Fatalf("locate golang.org/x/sys: %v", err)
	}
	dir := strings.TrimSpace(string(out))
	var buf bytes.Buffer
	buf.WriteString("// Code generated by mktables.go from golang.org/x/sys/unix; DO NOT EDIT.\n\n")
	buf.WriteString("package seccomp\n\n")
	for _, a := range []struct{ goarch, varName string }{{"amd64", "syscallsX86_64"}, {"arm64", "syscallsAArch64"}} {
		table := parse(filepath.Join(dir, "unix", "zsysnum_linux_"+a.goarch+".go"))
		names := make([]string, 0, len(table))
		for n := range table {
			names = append(names, n)
		}
		sort.Strings(names)
		fmt.Fprintf(&buf, "var %s = map[string]uint32{\n", a.varName)
		for _, n := range names {
			fmt.Fprintf(&buf, "\t%q: %d,\n", n, table[n])
		}
		buf.WriteString("}\n\n")
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("format: %v", err)
	}
	if _, err := os.Stdout.Write(src); err != nil {
		log.Fatal(err)
	}
}

func parse(path string) map[string]uint32 {
	f, err := os.Open(path)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	table := map[string]uint32{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		m := lineRE.FindStringSubmatch(sc.Text())
		if m == nil {
			continue
		}
		n, err := strconv.ParseUint(m[2], 10, 32)
		if err != nil {
			log.Fatalf("%s: %v", path, err)
		}
		table[strings.ToLower(m[1])] = uint32(n)
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	return table
}
